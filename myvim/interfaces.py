from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class ITextBuffer(Protocol):
    def line_count(self) -> int: ...
    def get_line(self, row: int) -> str: ...
    def set_line(self, row: int, text: str) -> None: ...
    def insert_line(self, row: int, text: str) -> None: ...
    def delete_line(self, row: int) -> None: ...
    def insert_text(self, row: int, col: int, text: str) -> None: ...
    def delete_range(self, row: int, start: int, end: int) -> str: ...
    def replace_range(self, row: int, start: int, end: int, text: str) -> None: ...
    def all_lines(self) -> list[str]: ...
    def restore(self, lines: list[str]) -> None: ...


@runtime_checkable
class IFileService(Protocol):
    def load(self, path: str) -> list[str]: ...
    def save(self, path: str, lines: list[str]) -> None: ...


@runtime_checkable
class IUndoService(Protocol):
    def push(self, snapshot: Any) -> None: ...
    def pop(self) -> Any: ...
    def clear(self) -> None: ...
    def is_empty(self) -> bool: ...


@runtime_checkable
class ISearchService(Protocol):
    def find(
        self,
        lines: list[str],
        start_row: int,
        start_col: int,
        query: str,
        forward: bool,
    ) -> tuple[int, int] | None: ...


@runtime_checkable
class IInput(Protocol):
    def get_key(self) -> int: ...
    def getmaxyx(self) -> tuple[int, int]: ...


@runtime_checkable
class IRenderTarget(Protocol):
    def clear(self) -> None: ...
    def refresh(self) -> None: ...
    def getmaxyx(self) -> tuple[int, int]: ...
    def addstr(self, y: int, x: int, text: str, attr: int = 0) -> None: ...
    def move(self, y: int, x: int) -> None: ...
    def attr_status(self) -> int: ...
    def attr_lineno(self) -> int: ...
    def attr_message(self) -> int: ...


@runtime_checkable
class IRenderer(Protocol):
    def render(self, model: "IModelView", mode_name: str, message: str) -> None: ...


@runtime_checkable
class IModelView(Protocol):
    """Минимальный срез модели, нужный View."""
    lines: Any                       # buffer
    row: int
    col: int
    filename: str | None
    modified: bool
    show_numbers: bool


@runtime_checkable
class IExCommand(Protocol):
    def matches(self, cmd: str) -> bool: ...
    def execute(self, cmd: str, ctx: Any) -> None: ...